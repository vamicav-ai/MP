export async function ensureMongoIndexes(database) {
  await Promise.all([
    database.collection("users").createIndex({ id: 1 }, { unique: true }),
    database.collection("users").createIndex({ email_key: 1 }, { unique: true }),
    database.collection("sessions").createIndex({ token_hash: 1 }, { unique: true }),
    database.collection("sessions").createIndex({ user_id: 1 }, { unique: true }),
    database.collection("sessions").createIndex({ expires_at: 1 }, { expireAfterSeconds: 0 }),
    database.collection("subjects").createIndex({ id: 1 }, { unique: true }),
    database.collection("subjects").createIndex({ name_key: 1 }, { unique: true }),
    database.collection("student_subjects").createIndex({ student_id: 1, subject_id: 1 }, { unique: true }),
    database.collection("teacher_subjects").createIndex({ teacher_id: 1, subject_id: 1 }, { unique: true }),
    database.collection("batches").createIndex({ id: 1 }, { unique: true }),
    database.collection("batch_subjects").createIndex({ batch_id: 1, subject_id: 1 }, { unique: true }),
    database.collection("enrollments").createIndex({ id: 1 }, { unique: true }),
    database.collection("enrollments").createIndex({ student_id: 1, batch_id: 1 }, { unique: true }),
    database.collection("offline_payment_requests").createIndex({ id: 1 }, { unique: true }),
    database.collection("offline_payment_requests").createIndex({ student_id: 1, batch_id: 1 }, { unique: true }),
    database.collection("classes").createIndex({ id: 1 }, { unique: true }),
    database.collection("classes").createIndex({ subject_id: 1, published: 1 }),
    database.collection("class_progress").createIndex({ student_id: 1, class_id: 1 }, { unique: true }),
    database.collection("reel_series").createIndex({ id: 1 }, { unique: true }),
    database.collection("reels").createIndex({ id: 1 }, { unique: true }),
    database.collection("reels").createIndex({ series_id: 1, sequence_number: 1 }, { unique: true }),
    database.collection("reel_progress").createIndex({ student_id: 1, reel_id: 1 }, { unique: true }),
    database.collection("notifications").createIndex({ id: 1 }, { unique: true }),
    database.collection("notifications").createIndex({ user_id: 1, created_at: -1 }),
    database.collection("audit_logs").createIndex({ id: 1 }, { unique: true }),
  ]);
}
